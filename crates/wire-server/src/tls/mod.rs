//! - [`x25519`]: X25519 鍵交換（RFC 7748・定数時間。Issue #955）。TLS 1.3
//!   の鍵交換グループとして採用
//!
//! key_share 拡張の解析（#954）・HKDF／鍵スケジュール（#956）・alert 型や
//! ハンドシェイク状態機械（#965）・接続への結線（#966 以降）はいずれも
//! 後続 sub-issue の担当であり、本モジュールは対象外のまま。

